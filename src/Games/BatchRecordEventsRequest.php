namespace Google\Service\Games;

class BatchRecordEventsRequest extends \Google\Collection
{
  protected $collection_key = 'events';
  /**
   * Optional. The DroidGuard blob generated by the client. This is used to
   * detect abuse signals from the devices
   *
   * @var string
   */
  public $droidGuardBlob;
  protected $eventsType = PlayerGameEvent::class;
  protected $eventsDataType = 'array';
  /**
   * Required. Application package name (e.g., "com.example.game").
   *
   * @var string
   */
  public $packageName;
  /**
   * Required. The time from the client when this specific batch of events was
   * submitted.
   *
   * @var string
   */
  public $requestTime;
  /**
   * Optional. The salt used to generate content binding for the DroidGuard
   * blob. This is used to prevent replay attacks.
   *
   * @var string
   */
  public $salt;

  /**
   * Optional. The DroidGuard blob generated by the client. This is used to
   * detect abuse signals from the devices
   *
   * @param string $droidGuardBlob
   */
  public function setDroidGuardBlob($droidGuardBlob)
  {
    $this->droidGuardBlob = $droidGuardBlob;
  }
  /**
   * @return string
   */
  public function getDroidGuardBlob()
  {
    return $this->droidGuardBlob;
  }
  /**
   * Required. A list of player game events to be recorded. Maximum of 30 events
   * per batch request.
   *
   * @param PlayerGameEvent[] $events
   */
  public function setEvents($events)
  {
    $this->events = $events;
  }
  /**
   * @return PlayerGameEvent[]
   */
  public function getEvents()
  {
    return $this->events;
  }
  /**
   * Required. Application package name (e.g., "com.example.game").
   *
   * @param string $packageName
   */
  public function setPackageName($packageName)
  {
    $this->packageName = $packageName;
  }
  /**
   * @return string
   */
  public function getPackageName()
  {
    return $this->packageName;
  }
  /**
   * Required. The time from the client when this specific batch of events was
   * submitted.
   *
   * @param string $requestTime
   */
  public function setRequestTime($requestTime)
  {
    $this->requestTime = $requestTime;
  }
  /**
   * @return string
   */
  public function getRequestTime()
  {
    return $this->requestTime;
  }
  /**
   * Optional. The salt used to generate content binding for the DroidGuard
   * blob. This is used to prevent replay attacks.
   *
   * @param string $salt
   */
  public function setSalt($salt)
  {
    $this->salt = $salt;
  }
  /**
   * @return string
   */
  public function getSalt()
  {
    return $this->salt;
  }
}

// Adding a class alias for backwards compatibility with the previous class name.
class_alias(BatchRecordEventsRequest::class, 'Google_Service_Games_BatchRecordEventsRequest');
