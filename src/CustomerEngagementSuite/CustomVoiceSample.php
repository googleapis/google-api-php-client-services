namespace Google\Service\CustomerEngagementSuite;

class CustomVoiceSample extends \Google\Collection
{
  /**
   * Unspecified instruction mode. Defaults to NO_INSTRUCTION.
   */
  public const VOICE_INSTRUCTION_MODE_VOICE_INSTRUCTION_MODE_UNSPECIFIED = 'VOICE_INSTRUCTION_MODE_UNSPECIFIED';
  /**
   * No voice instruction will be used.
   */
  public const VOICE_INSTRUCTION_MODE_NO_INSTRUCTION = 'NO_INSTRUCTION';
  /**
   * Voice instruction will be automatically generated by AI from the audio
   * sample.
   */
  public const VOICE_INSTRUCTION_MODE_GENERATE_INSTRUCTION = 'GENERATE_INSTRUCTION';
  /**
   * Custom voice instruction provided by the user.
   */
  public const VOICE_INSTRUCTION_MODE_CUSTOM_INSTRUCTION = 'CUSTOM_INSTRUCTION';
  protected $collection_key = 'warnings';
  /**
   * Optional. Consent audio for voice cloning.
   *
   * @var string
   */
  public $consentAudioGcsUri;
  /**
   * Optional. The user-defined name for the custom voice sample.
   *
   * @var string
   */
  public $name;
  /**
   * Output only. Synthesized preview audio for custom voice, formatted as
   * canonical WAV (LINEAR16, 24kHz, 16-bit, mono).
   *
   * @var string
   */
  public $previewAudioContent;
  /**
   * Optional. Text for synthesizing preview audio for custom voice.
   *
   * @var string
   */
  public $previewText;
  /**
   * Optional. Natural language instructions for voice style, tone, pacing, or
   * pronunciation.
   *
   * @var string
   */
  public $voiceInstruction;
  /**
   * Optional. Instruction mode for the voice sample. If unspecified, defaults
   * to NO_INSTRUCTION.
   *
   * @var string
   */
  public $voiceInstructionMode;
  /**
   * Optional. The Cloud Storage URI to the audio sample for voice cloning. The
   * audio sample should be a mono-channel, 24kHz WAV file.
   *
   * @var string
   */
  public $voiceSampleGcsUri;
  protected $warningsType = CustomVoiceSampleWarning::class;
  protected $warningsDataType = 'array';

  /**
   * Optional. Consent audio for voice cloning.
   *
   * @param string $consentAudioGcsUri
   */
  public function setConsentAudioGcsUri($consentAudioGcsUri)
  {
    $this->consentAudioGcsUri = $consentAudioGcsUri;
  }
  /**
   * @return string
   */
  public function getConsentAudioGcsUri()
  {
    return $this->consentAudioGcsUri;
  }
  /**
   * Optional. The user-defined name for the custom voice sample.
   *
   * @param string $name
   */
  public function setName($name)
  {
    $this->name = $name;
  }
  /**
   * @return string
   */
  public function getName()
  {
    return $this->name;
  }
  /**
   * Output only. Synthesized preview audio for custom voice, formatted as
   * canonical WAV (LINEAR16, 24kHz, 16-bit, mono).
   *
   * @param string $previewAudioContent
   */
  public function setPreviewAudioContent($previewAudioContent)
  {
    $this->previewAudioContent = $previewAudioContent;
  }
  /**
   * @return string
   */
  public function getPreviewAudioContent()
  {
    return $this->previewAudioContent;
  }
  /**
   * Optional. Text for synthesizing preview audio for custom voice.
   *
   * @param string $previewText
   */
  public function setPreviewText($previewText)
  {
    $this->previewText = $previewText;
  }
  /**
   * @return string
   */
  public function getPreviewText()
  {
    return $this->previewText;
  }
  /**
   * Optional. Natural language instructions for voice style, tone, pacing, or
   * pronunciation.
   *
   * @param string $voiceInstruction
   */
  public function setVoiceInstruction($voiceInstruction)
  {
    $this->voiceInstruction = $voiceInstruction;
  }
  /**
   * @return string
   */
  public function getVoiceInstruction()
  {
    return $this->voiceInstruction;
  }
  /**
   * Optional. Instruction mode for the voice sample. If unspecified, defaults
   * to NO_INSTRUCTION.
   *
   * Accepted values: VOICE_INSTRUCTION_MODE_UNSPECIFIED, NO_INSTRUCTION,
   * GENERATE_INSTRUCTION, CUSTOM_INSTRUCTION
   *
   * @param self::VOICE_INSTRUCTION_MODE_* $voiceInstructionMode
   */
  public function setVoiceInstructionMode($voiceInstructionMode)
  {
    $this->voiceInstructionMode = $voiceInstructionMode;
  }
  /**
   * @return self::VOICE_INSTRUCTION_MODE_*
   */
  public function getVoiceInstructionMode()
  {
    return $this->voiceInstructionMode;
  }
  /**
   * Optional. The Cloud Storage URI to the audio sample for voice cloning. The
   * audio sample should be a mono-channel, 24kHz WAV file.
   *
   * @param string $voiceSampleGcsUri
   */
  public function setVoiceSampleGcsUri($voiceSampleGcsUri)
  {
    $this->voiceSampleGcsUri = $voiceSampleGcsUri;
  }
  /**
   * @return string
   */
  public function getVoiceSampleGcsUri()
  {
    return $this->voiceSampleGcsUri;
  }
  /**
   * Output only. Warning messages encountered during voice clone processing
   * (e.g. low audio level).
   *
   * @param CustomVoiceSampleWarning[] $warnings
   */
  public function setWarnings($warnings)
  {
    $this->warnings = $warnings;
  }
  /**
   * @return CustomVoiceSampleWarning[]
   */
  public function getWarnings()
  {
    return $this->warnings;
  }
}

// Adding a class alias for backwards compatibility with the previous class name.
class_alias(CustomVoiceSample::class, 'Google_Service_CustomerEngagementSuite_CustomVoiceSample');
