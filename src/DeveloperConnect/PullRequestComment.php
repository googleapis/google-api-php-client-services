namespace Google\Service\DeveloperConnect;

class PullRequestComment extends \Google\Model
{
  /**
   * Output only. The username of the author.
   *
   * @var string
   */
  public $author;
  /**
   * Required. The body of the comment.
   *
   * @var string
   */
  public $body;
  /**
   * Output only. When the comment was created.
   *
   * @var string
   */
  public $createTime;
  /**
   * Output only. The ID of the comment.
   *
   * @var string
   */
  public $id;
  /**
   * Output only. When the comment was updated.
   *
   * @var string
   */
  public $updateTime;

  /**
   * Output only. The username of the author.
   *
   * @param string $author
   */
  public function setAuthor($author)
  {
    $this->author = $author;
  }
  /**
   * @return string
   */
  public function getAuthor()
  {
    return $this->author;
  }
  /**
   * Required. The body of the comment.
   *
   * @param string $body
   */
  public function setBody($body)
  {
    $this->body = $body;
  }
  /**
   * @return string
   */
  public function getBody()
  {
    return $this->body;
  }
  /**
   * Output only. When the comment was created.
   *
   * @param string $createTime
   */
  public function setCreateTime($createTime)
  {
    $this->createTime = $createTime;
  }
  /**
   * @return string
   */
  public function getCreateTime()
  {
    return $this->createTime;
  }
  /**
   * Output only. The ID of the comment.
   *
   * @param string $id
   */
  public function setId($id)
  {
    $this->id = $id;
  }
  /**
   * @return string
   */
  public function getId()
  {
    return $this->id;
  }
  /**
   * Output only. When the comment was updated.
   *
   * @param string $updateTime
   */
  public function setUpdateTime($updateTime)
  {
    $this->updateTime = $updateTime;
  }
  /**
   * @return string
   */
  public function getUpdateTime()
  {
    return $this->updateTime;
  }
}

// Adding a class alias for backwards compatibility with the previous class name.
class_alias(PullRequestComment::class, 'Google_Service_DeveloperConnect_PullRequestComment');
